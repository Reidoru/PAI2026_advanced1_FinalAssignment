def require_name_id(mujoco, model, object_type, name: str) -> int:
    idx = mujoco.mj_name2id(model, object_type, name)
    if idx < 0:
        raise RuntimeError(f"MuJoCo model is missing named object: {name}")
    return int(idx)


def load_policy_runtime(repo: Path, policy_path: Path | None = None):
    runtime_path = repo / "deploy" / "go2_runtime.py"
    if not runtime_path.exists():
        raise FileNotFoundError(f"Runtime not found: {runtime_path}")
    spec = importlib.util.spec_from_file_location("go2_upstream_runtime", runtime_path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot import policy runtime: {runtime_path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    chosen_policy = policy_path or (repo / "policy" / "go2_policy.onnx")
    if not chosen_policy.exists():
        raise FileNotFoundError(
            f"ONNX policy not found: {chosen_policy}\n"
            "Check the upstream checkout and policy file. Do not substitute an "
            "arbitrary ONNX model: the observation/action interface must match."
        )
    return module.Go2Policy(chosen_policy)


def _random_rgb(rng: random.Random, *, floor: bool = False):
    """Generate a readable random RGB color; floor is kept light, walls darker."""
    hue = rng.random()
    if floor:
        # Stronger chroma and a lower value prevent the floor tiles from
        # looking washed out under MuJoCo's lighting.
        saturation = rng.uniform(0.58, 0.82)
        value = rng.uniform(0.62, 0.82)
    else:
        saturation = rng.uniform(0.48, 0.82)
        value = rng.uniform(0.34, 0.66)
    return colorsys.hsv_to_rgb(hue, saturation, value)


def add_maze_to_scene(
    source_xml: Path,
    output_xml: Path,
    maze,
    cell_size: float,
    *,
    show_goal: bool = False,
    color_seed: int | None = None,
):
    """Add maze walls, randomized wall/floor colors, optional goal and overhead camera."""
    from maze_utils import maze_wall_segments

    rng = random.Random(color_seed)
    tree = ET.parse(source_xml)
    root = tree.getroot()
    worldbody = root.find("worldbody")
    if worldbody is None:
        raise RuntimeError(f"No <worldbody> in {source_xml}")

    # Remove elements generated by an earlier run.
    for node in list(worldbody):
        if node.tag == "geom" and (
            node.get("name", "").startswith("maze_wall_")
            or node.get("name", "").startswith("maze_goal_")
            or node.get("name", "").startswith("maze_floor_")
        ):
            worldbody.remove(node)

        if node.tag == "camera" and node.get("name") == "maze_overhead":
            worldbody.remove(node)

    # Randomize the existing floor geom. Removing a geom-level material reference
    # ensures that its rgba value is actually used instead of a shared material.
    floor_geoms = [g for g in root.iter("geom") if g.get("name") == "floor"]
    if not floor_geoms:
        raise RuntimeError(
            f"Could not find a geom named 'floor' in {source_xml}; "
            "floor color was not randomized."
        )
    floor_rgb = _random_rgb(rng, floor=True)
    
    # Add one independently colored visual tile for each maze cell.
    # The original floor remains underneath and continues to provide collision.
    tile_half_size = cell_size / 2.0
    tile_half_thickness = 0.001
    tile_center_z = 0.002

    for r in range(maze.rows):
        for c in range(maze.cols):
            tx, ty = cell_center(
                (r, c), maze.rows, maze.cols, cell_size
            )

            tile_rgb = _random_rgb(rng, floor=True)

            ET.SubElement(worldbody, "geom", {
                "name": f"maze_floor_{r}_{c}",
                "type": "box",
                "pos": (
                    f"{tx:.6f} {ty:.6f} {tile_center_z:.6f}"
                ),
                "size": (
                    f"{tile_half_size:.6f} "
                    f"{tile_half_size:.6f} "
                    f"{tile_half_thickness:.6f}"
                ),
                "rgba": "{:.3f} {:.3f} {:.3f} 1".format(*tile_rgb),

                # Visual only: collision is handled by the original floor.
                "contype": "0",
                "conaffinity": "0",
            })

    wall_height = 0.28
    wall_thickness = 0.06
    for i, (a, b) in enumerate(maze_wall_segments(maze, cell_size)):
        x1, y1 = a
        x2, y2 = b
        cx, cy = (x1+x2)/2.0, (y1+y2)/2.0
        length = math.hypot(x2-x1, y2-y1)
        if abs(x2-x1) < 1e-8:  # vertical segment
            size = f"{wall_thickness/2} {length/2 + 0.002} {wall_height/2}"
        else:  # horizontal segment
            size = f"{length/2 + 0.002} {wall_thickness/2} {wall_height/2}"
        wall_rgb = _random_rgb(rng, floor=False)
        ET.SubElement(worldbody, "geom", {
            "name": f"maze_wall_{i}",
            "type": "box",
            "pos": f"{cx:.6f} {cy:.6f} {wall_height/2:.6f}",
            "size": size,
            "rgba": "{:.3f} {:.3f} {:.3f} 1".format(*wall_rgb),
            "friction": "0.8 0.02 0.01",
            "condim": "3",
        })

    if show_goal:
        # The marker is visual-only and is disabled for depth-based wall detection.
        gx, gy = cell_center(maze.goal, maze.rows, maze.cols, cell_size)
        ET.SubElement(worldbody, "geom", {
            "name": "maze_goal_floor",
            "type": "box",
            "pos": f"{gx:.6f} {gy:.6f} 0.008",
            "size": f"{cell_size * 0.40:.6f} {cell_size * 0.40:.6f} 0.004",
            "rgba": "0.95 0.035 0.025 0.88",
            "contype": "0", "conaffinity": "0",
        })
        pole_height = 0.48
        ET.SubElement(worldbody, "geom", {
            "name": "maze_goal_flag_pole", "type": "cylinder",
            "pos": f"{gx:.6f} {gy:.6f} {pole_height / 2 + 0.02:.6f}",
            "size": "0.018 0.24", "rgba": "1.0 0.78 0.08 1",
            "contype": "0", "conaffinity": "0",
        })
        ET.SubElement(worldbody, "geom", {
            "name": "maze_goal_flag", "type": "box",
            "pos": f"{gx + 0.105:.6f} {gy:.6f} {pole_height * 0.82:.6f}",
            "size": "0.105 0.008 0.065", "rgba": "1.0 0.025 0.02 1",
            "contype": "0", "conaffinity": "0",
        })

    extent = max(maze.rows, maze.cols) * cell_size
    cam_z = max(4.0, extent * 1.25)
    ET.SubElement(worldbody, "camera", {
        "name": "maze_overhead",
        "pos": f"0 0 {cam_z:.4f}",
        "quat": "1 0 0 0",
        "fovy": "50",
    })

    output_xml.parent.mkdir(parents=True, exist_ok=True)
    tree.write(output_xml, encoding="utf-8", xml_declaration=True)


class Go2Simulation:
    def __init__(self, repo: Path, scene_xml: Path, policy_path: Path | None = None):
        try:
            import mujoco
        except ImportError as exc:
            raise RuntimeError("Install MuJoCo first: pip install mujoco==3.8.0") from exc
        self.mujoco = mujoco
        self.repo = repo
        self.policy = load_policy_runtime(repo, policy_path)
        self.model = mujoco.MjModel.from_xml_path(str(scene_xml))
        self.data = mujoco.MjData(self.model)

        self.base_id = require_name_id(
            mujoco, self.model, mujoco.mjtObj.mjOBJ_BODY, "base"
        )
        self.joint_ids = [
            require_name_id(mujoco, self.model, mujoco.mjtObj.mjOBJ_JOINT, n)
            for n in JOINT_NAMES_ROBOT_ORDER
        ]
        self.actuator_ids = [
            require_name_id(mujoco, self.model, mujoco.mjtObj.mjOBJ_ACTUATOR, n)
            for n in ACTUATOR_NAMES_ROBOT_ORDER
        ]
        self.qpos_addrs = [int(self.model.jnt_qposadr[j]) for j in self.joint_ids]
        self.dof_addrs = [int(self.model.jnt_dofadr[j]) for j in self.joint_ids]
        self.free_joint_id = None
        for jid in range(self.model.njnt):
            if self.model.jnt_type[jid] == mujoco.mjtJoint.mjJNT_FREE:
                self.free_joint_id = jid
                break
        if self.free_joint_id is None:
            raise RuntimeError("Go2 model has no free root joint")
        self.root_qpos_adr = int(self.model.jnt_qposadr[self.free_joint_id])
        self.root_dof_adr = int(self.model.jnt_dofadr[self.free_joint_id])
        self.wall_geom_ids = {
            gid for gid in range(self.model.ngeom)
            if (mujoco.mj_id2name(self.model, mujoco.mjtObj.mjOBJ_GEOM, gid) or "").startswith("maze_wall_")
        }
        self.floor_geom_id = mujoco.mj_name2id(
            self.model, mujoco.mjtObj.mjOBJ_GEOM, "floor"
        )
        self.camera_id = mujoco.mj_name2id(
            self.model, mujoco.mjtObj.mjOBJ_CAMERA, "maze_overhead"
        )
        self.reset()

    def reset(self, x=0.0, y=0.0, yaw=0.0):
        m, d = self.mujoco, self.data
        m.mj_resetData(self.model, d)
        # Reset to a policy-compatible pose. The root free-joint quaternion is w,x,y,z.
        d.qpos[self.root_qpos_adr:self.root_qpos_adr+7] = [
            x, y, 0.37, math.cos(yaw/2), 0.0, 0.0, math.sin(yaw/2)
        ]
        # Policy default pose is specified in the upstream runtime's Isaac joint order;
        # convert it into the model's limb-major order.
        default_isaac = np.asarray(self.policy.__class__.__module__ and
                                   sys.modules[self.policy.__class__.__module__].DEFAULT_ISAAC,
                                   dtype=np.float32)
        isaac_to_robot = np.asarray(
            sys.modules[self.policy.__class__.__module__].ISAAC_TO_ROBOT, dtype=int
        )
        default_robot = default_isaac[isaac_to_robot]
        for adr, val in zip(self.qpos_addrs, default_robot):
            d.qpos[adr] = float(val)
        d.qvel[:] = 0.0
        self.policy.prev_action[:] = 0.0
        m.mj_forward(self.model, d)
        self.last_command = np.zeros(3, dtype=np.float32)
        self.wall_contact_steps = 0

    def pose(self):
        qadr = self.root_qpos_adr
        pos = self.data.qpos[qadr:qadr+3].copy()
        quat = self.data.qpos[qadr+3:qadr+7].copy()
        return pos, quat, yaw_from_quat_wxyz(quat)

    def body_velocity(self):
        m, d = self.mujoco, self.data
        vel6 = np.zeros(6, dtype=np.float64)
        m.mj_objectVelocity(
            self.model, d, m.mjtObj.mjOBJ_BODY, self.base_id, vel6, 0
        )
        # MuJoCo returns angular then linear velocity in world coordinates when
        # flg_local=0. Rotate linear velocity to the body frame for policy tracking.
        pos, quat, yaw = self.pose()
        w, x, y, z = quat
        rot = np.array([
            [1-2*(y*y+z*z), 2*(x*y-z*w), 2*(x*z+y*w)],
            [2*(x*y+z*w), 1-2*(x*x+z*z), 2*(y*z-x*w)],
            [2*(x*z-y*w), 2*(y*z+x*w), 1-2*(x*x+y*y)],
        ], dtype=np.float64)
        lin_body = rot.T @ vel6[3:6]
        # yaw-rate command is world z angular velocity; near level, this is the
        # relevant component for tracking commanded yaw rate.
        return np.array([lin_body[0], lin_body[1], vel6[2]], dtype=np.float32)

    def command_step(self, command, physics_substeps=10):
        m, d = self.mujoco, self.data
        command = np.asarray(command, dtype=np.float32)
        pos, quat, yaw = self.pose()
        ang_world = np.zeros(3, dtype=np.float32)
        lin_world = np.zeros(3, dtype=np.float32)
        vel6 = np.zeros(6, dtype=np.float64)
        m.mj_objectVelocity(
            self.model, d, m.mjtObj.mjOBJ_BODY, self.base_id, vel6, 0
        )
        ang_world[:] = vel6[:3]
        lin_world[:] = vel6[3:6]
        joint_pos = np.array([d.qpos[a] for a in self.qpos_addrs], dtype=np.float32)
        joint_vel = np.array([d.qvel[a] for a in self.dof_addrs], dtype=np.float32)
        target = self.policy.step(
            quat=quat,
            ang_vel_world=ang_world,
            lin_vel_world=lin_world,
            joint_pos_robot=joint_pos,
            joint_vel_robot=joint_vel,
            command=command,
        )
        torque = self.policy.torques(target, joint_pos, joint_vel)
        # Respect actuator ctrl limits (Go2 Menagerie uses torque motors).
        for i, aid in enumerate(self.actuator_ids):
            lo, hi = self.model.actuator_ctrlrange[aid]
            d.ctrl[aid] = float(np.clip(torque[i], lo, hi))
        for _ in range(physics_substeps):
            m.mj_step(self.model, d)
        self.last_command = command.copy()
        if self.has_wall_contact():
            self.wall_contact_steps += 1

    def has_wall_contact(self):
        m, d = self.mujoco, self.data
        for i in range(d.ncon):
            con = d.contact[i]
            if int(con.geom1) in self.wall_geom_ids or int(con.geom2) in self.wall_geom_ids:
                return True
        return False

    def is_fallen(self):
        pos, quat, _ = self.pose()
        w, x, y, z = quat
        # world-z component of the robot's local up vector
        up_z = 1.0 - 2.0 * (x*x + y*y)
        return bool(pos[2] < 0.17 or up_z < 0.35)

    def render_viewer(self, viewer):
        if self.camera_id >= 0:
            viewer.cam.type = self.mujoco.mjtCamera.mjCAMERA_FIXED
            viewer.cam.fixedcamid = int(self.camera_id)
        viewer.sync()




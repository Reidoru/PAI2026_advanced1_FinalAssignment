def render_depth_image(model, data, camera_name="maze_overhead", width=640, height=480):
    """Render metric depth (meters) from a named MuJoCo camera."""
    import mujoco

    renderer = None
    try:
        renderer = mujoco.Renderer(model, height=height, width=width)
        renderer.enable_depth_rendering()
        renderer.update_scene(data, camera=camera_name)
        depth_image = renderer.render().copy()
    finally:
        if renderer is not None:
            try:
                renderer.disable_depth_rendering()
            finally:
                renderer.close()

    if depth_image.shape != (height, width):
        raise RuntimeError(
            f"Unexpected depth image shape {depth_image.shape}; expected {(height, width)}"
        )
    if not np.issubdtype(depth_image.dtype, np.floating):
        depth_image = depth_image.astype(np.float32)
    return depth_image


def depth_to_world_points(depth_image, model, data, camera_name="maze_overhead"):
    """Back-project a metric MuJoCo depth image into world XYZ coordinates.

    MuJoCo's classic Renderer returns depth values in meters. The depth is the
    distance along the camera view axis (not Euclidean ray length). Camera local
    axes follow OpenGL convention: +X right, +Y up, and -Z forward.
    Invalid/background pixels are returned as NaN XYZ values.
    """
    import mujoco

    depth = np.asarray(depth_image, dtype=np.float32)
    if depth.ndim != 2:
        raise ValueError(f"depth_image must be 2-D; got shape {depth.shape}")
    height, width = depth.shape

    camera_id = mujoco.mj_name2id(
        model, mujoco.mjtObj.mjOBJ_CAMERA, camera_name
    )
    if camera_id < 0:
        raise ValueError(f"Camera not found: {camera_name}")

    # The camera transforms in mjData are updated by mj_forward.
    mujoco.mj_forward(model, data)
    fovy = float(model.cam_fovy[camera_id])
    focal = height / (2.0 * math.tan(math.radians(fovy) / 2.0))
    cx = width / 2.0
    cy = height / 2.0

    u_grid, v_grid = np.meshgrid(
        np.arange(width, dtype=np.float32) + 0.5,
        np.arange(height, dtype=np.float32) + 0.5,
    )

    # The classic Renderer converts the OpenGL depth buffer to metric depth.
    # Pixels at the far clipping plane represent background, not scene surfaces.
    far_clip = float(model.vis.map.zfar * model.stat.extent)
    valid = np.isfinite(depth) & (depth > 0.0) & (depth < far_clip * 0.999)
    safe_depth = np.where(valid, depth, 0.0)

    x_cam = (u_grid - cx) * safe_depth / focal
    y_cam = (cy - v_grid) * safe_depth / focal
    z_cam = -safe_depth
    camera_points = np.stack((x_cam, y_cam, z_cam), axis=-1)

    rotation = np.asarray(data.cam_xmat[camera_id], dtype=np.float64).reshape(3, 3)
    translation = np.asarray(data.cam_xpos[camera_id], dtype=np.float64)
    world_points = camera_points @ rotation.T + translation
    world_points[~valid] = np.nan
    return world_points.astype(np.float32)


def detect_wall_between_cells(
    world_points,
    cell_a,
    cell_b,
    rows,
    cols,
    cell_size,
    *,
    wall_thickness=0.06,
    wall_height=0.28,
    floor_z=0.0,
    height_threshold=0.14,
    band_margin=0.045,
    wall_ratio_threshold=0.22,
    passage_ratio_threshold=0.08,
    min_valid_points=8,
):
    """Classify one shared cell boundary as 'wall', 'passage', or 'unknown'."""
    points = np.asarray(world_points)
    if points.ndim != 3 or points.shape[2] != 3:
        raise ValueError("world_points must have shape (height, width, 3)")

    ra, ca = cell_a
    rb, cb = cell_b
    if not (0 <= ra < rows and 0 <= ca < cols and 0 <= rb < rows and 0 <= cb < cols):
        raise ValueError("cell coordinates are outside the maze")
    if abs(ra - rb) + abs(ca - cb) != 1:
        raise ValueError("cell_a and cell_b must be orthogonally adjacent")

    ax, ay = cell_center(cell_a, rows, cols, cell_size)
    bx, by = cell_center(cell_b, rows, cols, cell_size)
    band_half_width = wall_thickness / 2.0 + band_margin
    along_half_length = cell_size * 0.35  # ignore corner junctions

    if ra == rb:  # east-west neighbors: shared boundary is a vertical line
        boundary_x = (ax + bx) / 2.0
        along_center = (ay + by) / 2.0
        region = (
            (np.abs(points[..., 0] - boundary_x) <= band_half_width)
            & (np.abs(points[..., 1] - along_center) <= along_half_length)
        )
    else:  # north-south neighbors: shared boundary is a horizontal line
        boundary_y = (ay + by) / 2.0
        along_center = (ax + bx) / 2.0
        region = (
            (np.abs(points[..., 1] - boundary_y) <= band_half_width)
            & (np.abs(points[..., 0] - along_center) <= along_half_length)
        )

    finite = np.all(np.isfinite(points), axis=-1)
    selected = points[region & finite]
    valid_count = int(selected.shape[0])
    if valid_count < min_valid_points:
        return "unknown", 0.0, valid_count

    # The wall top is at floor_z + wall_height; the floor is near floor_z.
    elevated_count = int(np.count_nonzero(selected[:, 2] > floor_z + height_threshold))
    elevated_ratio = elevated_count / valid_count
    if elevated_ratio >= wall_ratio_threshold:
        result = "wall"
    elif elevated_ratio <= passage_ratio_threshold:
        result = "passage"
    else:
        result = "unknown"
    return result, float(elevated_ratio), valid_count


def generate_maze_from_depth(
    world_points,
    rows,
    cols,
    cell_size,
    start,
    goal,
    *,
    unknown_as_wall=True,
    **detector_options,
):
    """Build an existing Maze object from depth-based boundary classifications.

    Returns (estimated_maze, diagnostics). Unknown edges are conservatively
    treated as walls by default, while their locations remain in diagnostics.
    """
    from maze_utils import OPPOSITE

    passages = {(r, c): set() for r in range(rows) for c in range(cols)}
    edge_results = {}
    unknown_edges = []

    for r in range(rows):
        for c in range(cols):
            cell = (r, c)
            for direction, neighbor in (
                ("E", (r, c + 1)) if c + 1 < cols else (None, None),
                ("S", (r + 1, c)) if r + 1 < rows else (None, None),
            ):
                if direction is None:
                    continue
                result, ratio, count = detect_wall_between_cells(
                    world_points, cell, neighbor, rows, cols, cell_size,
                    **detector_options,
                )
                edge_key = f"{r},{c}-{neighbor[0]},{neighbor[1]}"
                edge_results[edge_key] = {
                    "cell_a": cell,
                    "cell_b": neighbor,
                    "direction": direction,
                    "classification": result,
                    "elevated_ratio": ratio,
                    "valid_points": count,
                }
                if result == "passage" or (result == "unknown" and not unknown_as_wall):
                    passages[cell].add(direction)
                    passages[neighbor].add(OPPOSITE[direction])
                if result == "unknown":
                    unknown_edges.append(edge_key)

    estimated_maze = Maze(rows, cols, passages, tuple(start), tuple(goal))
    diagnostics = {
        "edge_results": edge_results,
        "unknown_edges": unknown_edges,
        "unknown_count": len(unknown_edges),
        "internal_edge_count": len(edge_results),
        "unknown_as_wall": bool(unknown_as_wall),
    }
    return estimated_maze, diagnostics


def compare_mazes(true_maze, estimated_maze, edge_results=None):
    """Compare internal wall/passage labels; unknown observations are omitted."""
    if (true_maze.rows, true_maze.cols) != (estimated_maze.rows, estimated_maze.cols):
        raise ValueError("true_maze and estimated_maze must have equal dimensions")

    tp = fp = tn = fn = skipped_unknown = 0
    for r in range(true_maze.rows):
        for c in range(true_maze.cols):
            for direction, neighbor in (
                ("E", (r, c + 1)) if c + 1 < true_maze.cols else (None, None),
                ("S", (r + 1, c)) if r + 1 < true_maze.rows else (None, None),
            ):
                if direction is None:
                    continue
                edge_key = f"{r},{c}-{neighbor[0]},{neighbor[1]}"
                if edge_results is not None:
                    item = edge_results.get(edge_key)
                    if item is not None and item["classification"] == "unknown":
                        skipped_unknown += 1
                        continue
                true_wall = direction not in true_maze.passages[(r, c)]
                predicted_wall = direction not in estimated_maze.passages[(r, c)]
                if true_wall and predicted_wall:
                    tp += 1
                elif not true_wall and predicted_wall:
                    fp += 1
                elif not true_wall and not predicted_wall:
                    tn += 1
                else:
                    fn += 1

    total = tp + fp + tn + fn
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    accuracy = (tp + tn) / total if total else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    all_edges = total + skipped_unknown
    return {
        "tp_wall_correct": tp,
        "fp_passage_misclassified_as_wall": fp,
        "tn_passage_correct": tn,
        "fn_wall_missed": fn,
        "unknown_skipped": skipped_unknown,
        "evaluated_edges": total,
        "total_internal_edges": all_edges,
        "coverage": total / all_edges if all_edges else 0.0,
        "accuracy": accuracy,
        "precision_wall": precision,
        "recall_wall": recall,
        "f1_wall": f1,
    }



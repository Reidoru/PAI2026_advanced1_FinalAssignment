def run_walk(args):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import mujoco
    import mujoco.viewer

    repo = args.repo.resolve()
    source_scene = repo / "assets" / "unitree_go2" / "scene.xml"
    if not source_scene.exists():
        raise FileNotFoundError(f"Go2 scene XML not found: {source_scene}")
    # A plain scene for locomotion performance test; keep fixed overhead camera available.
    empty_maze = generate_maze(2, 2, seed=args.seed)
    temp_scene = repo / "assets" / "unitree_go2" / "_generated_walk_scene.xml"
    add_maze_to_scene(source_scene, temp_scene, empty_maze, cell_size=0.7)
    # For walking-only test, walls are far away from the origin but still in the model.
    sim = Go2Simulation(repo, temp_scene, args.policy)
    sim.reset()
    sequence = [
        ("forward", np.array([0.35, 0.0, 0.0]), 3.0),
        ("stop", np.array([0.0, 0.0, 0.0]), 1.0),
        ("turn_left", np.array([0.0, 0.0, 0.55]), 2.0),
        ("forward_and_turn", np.array([0.30, 0.0, 0.45]), 3.0),
        ("strafe_left", np.array([0.0, 0.20, 0.0]), 2.0),
        ("stop", np.array([0.0, 0.0, 0.0]), 1.0),
    ]
    control_hz = 50.0
    physics_substeps = max(1, int(round((1.0/control_hz) / sim.model.opt.timestep)))
    logs = []
    viewer = None
    if not args.headless:
        viewer = mujoco.viewer.launch_passive(sim.model, sim.data)
        sim.render_viewer(viewer)

    try:
        t = 0.0
        for label, command, duration in sequence:
            for _ in range(int(duration * control_hz)):
                if viewer is not None and not viewer.is_running():
                    return
                sim.command_step(command, physics_substeps=physics_substeps)
                measured = sim.body_velocity()
                pos, quat, yaw = sim.pose()
                logs.append({
                    "time_s": t, "phase": label,
                    "cmd_vx": float(command[0]), "cmd_vy": float(command[1]),
                    "cmd_yaw": float(command[2]),
                    "meas_vx": float(measured[0]), "meas_vy": float(measured[1]),
                    "meas_yaw": float(measured[2]),
                    "x": float(pos[0]), "y": float(pos[1]), "z": float(pos[2]),
                    "yaw": float(yaw), "fallen": sim.is_fallen(),
                })
                if viewer is not None:
                    sim.render_viewer(viewer)
                t += 1.0/control_hz
                if sim.is_fallen():
                    print(f"[WARN] Robot appears fallen at t={t:.2f}s; stopping test.")
                    break
            if sim.is_fallen():
                break
    finally:
        if viewer is not None:
            viewer.close()
        temp_scene.unlink(missing_ok=True)

    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=True)
    (out / "walk_metrics.json").write_text(json.dumps(logs, indent=2), encoding="utf-8")
    if not logs:
        raise RuntimeError("No simulation steps were recorded.")
    ts = np.array([r["time_s"] for r in logs])
    fig, axes = plt.subplots(3, 1, figsize=(11, 8), sharex=True)
    for ax, key, title, unit in [
        (axes[0], "vx", "Forward velocity", "m/s"),
        (axes[1], "vy", "Lateral velocity", "m/s"),
        (axes[2], "yaw", "Yaw rate", "rad/s"),
    ]:
        ax.plot(ts, [r[f"cmd_{key}"] for r in logs], label="command", linewidth=1.8)
        ax.plot(ts, [r[f"meas_{key}"] for r in logs], label="measured", linewidth=1.2)
        ax.set_ylabel(unit)
        ax.set_title(title)
        ax.grid(True, alpha=0.3)
        ax.legend(loc="upper right")
    axes[-1].set_xlabel("time (s)")
    fig.tight_layout()
    fig.savefig(out / "walk_tracking.png", dpi=160)
    plt.close(fig)
    print(f"Saved: {out / 'walk_tracking.png'}")
    print(f"Saved: {out / 'walk_metrics.json'}")
    print("Interpretation: compare command and measured curves. Large tracking error or a fall "
          "means the policy/runtime/model combination is not ready for maze navigation.")


def waypoint_command(sim: Go2Simulation, target_xy, max_speed=0.30):
    """Track a waypoint while keeping the learned walking gait active.

    A zero/near-zero forward command during a large heading correction can
    cause this velocity-conditioned policy to lose its walking gait. Keep a
    modest forward command while turning, then reduce speed near the waypoint.
    """
    pos, quat, yaw = sim.pose()
    dx = float(target_xy[0] - pos[0])
    dy = float(target_xy[1] - pos[1])
    distance = math.hypot(dx, dy)
    desired_yaw = math.atan2(dy, dx)
    yaw_error = wrap_angle(desired_yaw - yaw)
    yaw_rate = float(np.clip(1.25 * yaw_error, -0.65, 0.65))

    if abs(yaw_error) > 0.40:
        # Keep the gait active without driving at full speed through a turn.
        vx = float(min(max_speed, max(0.10, 0.40 * max_speed)))
    else:
        # Do not impose a minimum crawl speed when almost at the waypoint.
        vx = float(np.clip(0.8 * distance, 0.0, max_speed))

    return np.array([vx, 0.0, yaw_rate], dtype=np.float32), distance, yaw_error


def run_maze(args):
    import mujoco
    import mujoco.viewer

    repo = args.repo.resolve()
    source_scene = repo / "assets" / "unitree_go2" / "scene.xml"
    if not source_scene.exists():
        raise FileNotFoundError(f"Go2 scene XML not found: {source_scene}")

    # Keep the generated maze as ground truth only. The planner will use the
    # separately reconstructed estimated_maze below.
    true_maze = generate_maze(args.rows, args.cols, args.seed)
    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=True)

    scene_out = repo / "assets" / "unitree_go2" / "_generated_maze_scene.xml"
    add_maze_to_scene(
        source_scene, scene_out, true_maze, args.cell_size,
        show_goal=True, color_seed=args.color_seed,
    )
    sim = Go2Simulation(repo, scene_out, args.policy)

    viewer = None
    video_renderer = None
    video_writer = None
    try:
        # Move the robot outside the overhead camera's view before taking the
        # static map image. No physics steps are run in this temporary pose.
        sim.reset(x=100.0, y=100.0, yaw=0.0)
        mujoco.mj_forward(sim.model, sim.data)
        depth_image = render_depth_image(
            sim.model, sim.data,
            camera_name="maze_overhead",
            width=args.depth_width,
            height=args.depth_height,
        )
        np.save(out / "maze_depth.npy", depth_image)
        save_depth_visualization(depth_image, out / "maze_depth.png")

        world_points = depth_to_world_points(
            depth_image, sim.model, sim.data, camera_name="maze_overhead"
        )
        estimated_maze, perception = generate_maze_from_depth(
            world_points,
            args.rows,
            args.cols,
            args.cell_size,
            true_maze.start,
            true_maze.goal,
            wall_thickness=0.06,
            wall_height=0.28,
            floor_z=args.floor_z,
            height_threshold=args.wall_height_threshold,
            band_margin=args.wall_band_margin,
            wall_ratio_threshold=args.wall_ratio_threshold,
            passage_ratio_threshold=args.passage_ratio_threshold,
            min_valid_points=args.min_boundary_points,
            unknown_as_wall=True,
        )
        comparison = compare_mazes(
            true_maze, estimated_maze, perception["edge_results"]
        )

        estimated_path = astar(estimated_maze)
        plot_maze(
            estimated_maze, estimated_path, args.cell_size,
            str(out / "maze_estimated_astar_plan.png"),
        )
        # Also save the ground-truth map for side-by-side debugging.
        true_path = astar(true_maze)
        plot_maze(
            true_maze, true_path, args.cell_size,
            str(out / "maze_ground_truth.png"),
        )
        (out / "maze_perception.json").write_text(json.dumps({
            "seed": args.seed,
            "color_seed": args.color_seed,
            "rows": args.rows,
            "cols": args.cols,
            "cell_size_m": args.cell_size,
            "start": true_maze.start,
            "goal": true_maze.goal,
            "depth_image_shape": list(depth_image.shape),
            "depth_min_m": float(np.nanmin(depth_image)),
            "depth_max_m": float(np.nanmax(depth_image)),
            "perception": perception,
            "comparison": comparison,
            "estimated_astar_path": estimated_path,
            "estimated_astar_path_edges": max(0, len(estimated_path) - 1),
        }, indent=2), encoding="utf-8")

        print("Depth-based maze reconstruction:")
        print(json.dumps(comparison, indent=2))
        print(f"Unknown boundaries: {perception['unknown_count']} / {perception['internal_edge_count']}")
        print(f"Saved: {out / 'maze_depth.npy'}")
        print(f"Saved: {out / 'maze_depth.png'}")
        print(f"Saved: {out / 'maze_estimated_astar_plan.png'}")
        print(f"Saved: {out / 'maze_perception.json'}")

        if not estimated_path:
            raise RuntimeError(
                "A* could not find a route in the depth-estimated maze. "
                "Inspect maze_depth.png, maze_ground_truth.png, "
                "maze_estimated_astar_plan.png and maze_perception.json. "
                "The robot will not be started using the ground-truth route."
            )

        # Only after perception is complete do we place the robot at the start.
        sx, sy = cell_center(true_maze.start, true_maze.rows, true_maze.cols, args.cell_size)
        gx, gy = cell_center(true_maze.goal, true_maze.rows, true_maze.cols, args.cell_size)
        sim.reset(x=sx, y=sy, yaw=0.0)

        if not args.headless:
            viewer = mujoco.viewer.launch_passive(sim.model, sim.data)
            sim.render_viewer(viewer)

        # 動画出力はシミュレーションの制御処理に干渉しない。
        try:
            import cv2
        except ImportError as exc:
            raise RuntimeError(
                "Video export requires OpenCV. Install it with: pip install opencv-python"
            ) from exc

        video_fps = float(args.video_fps)
        if video_fps <= 0:
            raise ValueError("--video-fps must be greater than zero")

        video_path = (
            args.video_output or (out / "go2_maze_demo.mp4")
        ).resolve()
        video_path.parent.mkdir(parents=True, exist_ok=True)

        fourcc = cv2.VideoWriter_fourcc(*"mp4v")
        video_writer = cv2.VideoWriter(
            str(video_path), fourcc, video_fps, (1920, 1080)
        )

        if not video_writer.isOpened():
            raise RuntimeError(
                f"Could not open video output: {video_path}. "
                "Check that the OpenCV video codec is available."
            )

        route_bgr = cv2.imread(str(out / "maze_estimated_astar_plan.png"))
        depth_bgr = cv2.imread(str(out / "maze_depth.png"))

        if route_bgr is None or depth_bgr is None:
            raise RuntimeError("Could not load the generated route/depth preview images.")

        video_renderer = mujoco.Renderer(
            sim.model, height=360, width=640
        )
        video_renderer.update_scene(sim.data, camera="maze_overhead")
        initial_rgb = video_renderer.render().copy()

        initial_stats = {
            "time_s": 0.0,
            "waypoint": 0,
            "x": sx,
            "y": sy,
            "yaw": 0.0,
            "goal_distance": math.hypot(gx - sx, gy - sy),
            "waypoint_distance": 0.0,
            "yaw_error": 0.0,
            "cmd_vx": 0.0,
            "cmd_yaw": 0.0,
            "meas_vx": 0.0,
            "collisions": 0,
            "accuracy": comparison["accuracy"],
            "coverage": comparison["coverage"],
            "unknown": perception["unknown_count"],
            "progress": 0.0,
        }

        intro = compose_video_frame(
            cv2, initial_rgb, route_bgr, depth_bgr, initial_stats,
            stage="DEPTH PERCEPTION | MAZE RECONSTRUCTION | A* PLANNING",
        )

        # 冒頭3秒は認識結果と経路を表示する。
        for _ in range(max(1, int(round(3.0 * video_fps)))):
            video_writer.write(intro)

        control_hz = 50.0
        frame_stride = max(1, int(round(control_hz / video_fps)))

        last_video_rgb = initial_rgb
        last_video_stats = initial_stats

        control_hz = 50.0
        physics_substeps = max(1, int(round((1.0/control_hz) / sim.model.opt.timestep)))
        path = estimated_path
        waypoint_index = 1 if len(path) > 1 else 0
        t = 0.0
        records = []
        success = False
        collision_steps = 0
        max_steps = int(args.max_seconds * control_hz)
        for step in range(max_steps):
            if viewer is not None and not viewer.is_running():
                break
            pos, quat, yaw = sim.pose()
            distance_goal = math.hypot(gx - pos[0], gy - pos[1])
            if distance_goal < args.goal_tolerance:
                success = True
                break
            if sim.is_fallen():
                print(f"[FAIL] Robot fell at t={t:.2f}s.")
                break

            while waypoint_index < len(path)-1:
                wx, wy = cell_center(path[waypoint_index], true_maze.rows, true_maze.cols, args.cell_size)
                if math.hypot(wx-pos[0], wy-pos[1]) < args.waypoint_tolerance:
                    waypoint_index += 1
                else:
                    break
            target = cell_center(path[waypoint_index], true_maze.rows, true_maze.cols, args.cell_size)
            command, d_waypoint, yaw_error = waypoint_command(sim, target, args.max_speed)
            sim.command_step(command, physics_substeps=physics_substeps)
            if sim.has_wall_contact():
                collision_steps += 1
            pos, quat, yaw = sim.pose()
            measured = sim.body_velocity()
            records.append({
                "time_s": t, "x": float(pos[0]), "y": float(pos[1]), "z": float(pos[2]),
                "yaw": float(yaw), "waypoint_index": waypoint_index,
                "target_x": float(target[0]), "target_y": float(target[1]),
                "distance_to_goal": float(math.hypot(gx-pos[0], gy-pos[1])),
                "distance_to_waypoint": float(d_waypoint), "yaw_error": float(yaw_error),
                "cmd_vx": float(command[0]), "cmd_vy": float(command[1]),
                "cmd_yaw": float(command[2]), "meas_vx": float(measured[0]),
                "meas_vy": float(measured[1]), "meas_yaw": float(measured[2]),
                "wall_contact": bool(sim.has_wall_contact()), "fallen": sim.is_fallen(),
            })
            if viewer is not None:
                sim.render_viewer(viewer)
            t += 1.0/control_hz

            current_goal_distance = math.hypot(gx - pos[0], gy - pos[1])

            last_video_stats = {
                "time_s": t,
                "waypoint": waypoint_index,
                "x": float(pos[0]),
                "y": float(pos[1]),
                "yaw": float(yaw),
                "goal_distance": current_goal_distance,
                "waypoint_distance": float(d_waypoint),
                "yaw_error": float(yaw_error),
                "cmd_vx": float(command[0]),
                "cmd_yaw": float(command[2]),
                "meas_vx": float(measured[0]),
                "collisions": collision_steps,
                "accuracy": comparison["accuracy"],
                "coverage": comparison["coverage"],
                "unknown": perception["unknown_count"],
                "progress": min(1.0, t / max(args.max_seconds, 1e-9)),
            }

            # 50Hzのシミュレーションから25fpsで動画を記録する。
            if step % frame_stride == 0 or step == max_steps - 1:
                video_renderer.update_scene(sim.data, camera="maze_overhead")
                last_video_rgb = video_renderer.render().copy()

                video_writer.write(
                    compose_video_frame(
                        cv2, last_video_rgb, route_bgr,
                        depth_bgr, last_video_stats
                    )
                )

        final_pos, _, final_yaw = sim.pose()
        summary = {
            "success": bool(success),
            "seed": args.seed,
            "rows": args.rows, "cols": args.cols, "cell_size_m": args.cell_size,
            "planner_map": "depth_estimated_maze",
            "astar_path_edges": max(0, len(path)-1),
            "simulated_time_s": round(t, 3),
            "final_x": float(final_pos[0]), "final_y": float(final_pos[1]),
            "final_yaw_rad": float(final_yaw),
            "distance_to_goal_m": float(math.hypot(gx-final_pos[0], gy-final_pos[1])),
            "wall_contact_steps": int(collision_steps),
            "fell": bool(sim.is_fallen()),
            "num_control_steps": len(records),
            "perception_accuracy": comparison["accuracy"],
            "perception_coverage": comparison["coverage"],
            "unknown_boundaries": perception["unknown_count"],
        }
        (out / "maze_run.json").write_text(json.dumps({
            "summary": summary, "steps": records,
            "perception": perception, "comparison": comparison,
        }, indent=2), encoding="utf-8")
        print(json.dumps(summary, indent=2))
        print(f"Saved: {out / 'maze_run.json'}")
        if not success:
            print("[NOTE] The estimated map produced an A* route, but the robot did not reach the goal. "
                  "This may be a locomotion/control issue rather than a perception issue.")
        final_stats = dict(last_video_stats)
        final_stats.update({
            "time_s": t,
            "x": float(final_pos[0]),
            "y": float(final_pos[1]),
            "yaw": float(final_yaw),
            "goal_distance": summary["distance_to_goal_m"],
            "collisions": collision_steps,
            "progress": (
                1.0 if success
                else min(1.0, t / max(args.max_seconds, 1e-9))
            ),
        })

        final_stage = (
            "SUCCESS | GOAL REACHED"
            if success
            else "RUN ENDED | GOAL NOT REACHED"
        )

        final_frame = compose_video_frame(
            cv2, last_video_rgb, route_bgr,
            depth_bgr, final_stats,
            stage=final_stage,
        )

        # 最後の結果を4秒間表示する。
        for _ in range(max(1, int(round(4.0 * video_fps)))):
            video_writer.write(final_frame)

        print(f"Saved video: {video_path}")
    finally:
        if viewer is not None:
            viewer.close()
        scene_out.unlink(missing_ok=True)

        if video_renderer is not None:
            video_renderer.close()

        if video_writer is not None:
            video_writer.release()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=["walk", "maze"], default="walk")
    parser.add_argument("--repo", type=Path,
                        default=Path("../go2-quadruped-locomotion-mujoco"),
                        help="path to the upstream Go2 locomotion repository")
    parser.add_argument("--policy", type=Path, default=None,
                        help="optional path to matching go2_policy.onnx")
    parser.add_argument("--output", type=Path, default=Path("outputs"))
    parser.add_argument(
        "--video-output",
        type=Path,
        default=None,
        help="MP4 output path (default: <output>/go2_maze_demo.mp4)",
    )

    parser.add_argument(
        "--video-fps",
        type=float,
        default=25.0,
        help="video frame rate; simulation remains at 50 Hz",
    )
    parser.add_argument("--seed", type=int, default=32)
    parser.add_argument("--rows", type=int, default=7)
    parser.add_argument("--cols", type=int, default=7)
    parser.add_argument("--cell-size", type=float, default=1.0)
    parser.add_argument("--color-seed", type=int, default=None,
                        help="optional seed for randomized wall/floor colors")
    parser.add_argument("--depth-width", type=int, default=640)
    parser.add_argument("--depth-height", type=int, default=480)
    parser.add_argument("--floor-z", type=float, default=0.0)
    parser.add_argument("--wall-height-threshold", type=float, default=0.14,
                        help="Z threshold above floor for detecting wall-top pixels")
    parser.add_argument("--wall-band-margin", type=float, default=0.045,
                        help="extra half-width around the known wall thickness")
    parser.add_argument("--wall-ratio-threshold", type=float, default=0.22)
    parser.add_argument("--passage-ratio-threshold", type=float, default=0.08)
    parser.add_argument("--min-boundary-points", type=int, default=8)
    parser.add_argument("--max-seconds", type=float, default=600)
    parser.add_argument("--max-speed", type=float, default=0.40)
    parser.add_argument("--goal-tolerance", type=float, default=0.28)
    parser.add_argument("--waypoint-tolerance", type=float, default=0.35)
    parser.add_argument("--headless", action="store_true",
                        help="run without the interactive MuJoCo viewer")
    args = parser.parse_args()

    if not args.repo.exists():
        raise FileNotFoundError(
            f"Upstream repository not found: {args.repo.resolve()}\n"
            "Clone https://github.com/FERBIN12/go2-quadruped-locomotion-mujoco "
            "and pass --repo with its directory."
        )
    if args.cell_size < 0.75:
        raise ValueError("Use cell-size >= 0.75 m initially; tighter corridors may hit the robot.")
    if args.mode == "walk":
        run_walk(args)
    else:
        run_maze(args)


if __name__ == "__main__":
    main()
